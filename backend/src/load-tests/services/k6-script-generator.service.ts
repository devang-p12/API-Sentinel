import { Injectable } from '@nestjs/common';
import { LoadTest, LoadTestMode } from '@prisma/client';

@Injectable()
export class K6ScriptGeneratorService {
  /**
   * Generates a self-contained, sanitized k6 script for the specified load test.
   * Uses strict JSON serialization to avoid code injection or syntax errors.
   */
  generateScript(loadTest: LoadTest, baseUrl?: string | null): string {
    const targetUrl = this.resolveTargetUrl(loadTest.url, baseUrl, loadTest.queryParams);
    const headers = this.resolveHeaders(loadTest.headers, loadTest.authentication, loadTest.method);
    const hasBody =
      ['POST', 'PUT', 'PATCH'].includes(loadTest.method) &&
      loadTest.body &&
      loadTest.body.trim().length > 0;

    const timeoutMs = (loadTest.timeout || 5) * 1000;

    let scenarioConfig: string;
    if (loadTest.mode === LoadTestMode.REQUEST_COUNT) {
      const iterations = loadTest.requestCount || 100;
      const maxDurationSecs = Math.max(loadTest.duration || 3600, 3600);
      scenarioConfig = `
      executor: 'shared-iterations',
      vus: ${loadTest.virtualUsers},
      iterations: ${iterations},
      maxDuration: '${maxDurationSecs}s',
      gracefulStop: '5s',`;
    } else {
      const durationSecs = loadTest.duration || 60;
      scenarioConfig = `
      executor: 'constant-vus',
      vus: ${loadTest.virtualUsers},
      duration: '${durationSecs}s',
      gracefulStop: '5s',`;
    }

    return `// Auto-generated by API Sentinel Load Testing Engine
import http from 'k6/http';
import { check } from 'k6';

export const options = {
  scenarios: {
    sentinel_load_test: {${scenarioConfig}
    },
  },
  summaryTrendStats: ['avg', 'min', 'med', 'max', 'p(90)', 'p(95)', 'p(99)'],
  discardResponseBodies: false,
};

const TARGET_URL = ${JSON.stringify(targetUrl)};
const PARAMS = {
  timeout: '${timeoutMs}ms',
  headers: ${JSON.stringify(headers)},
  tags: { load_test_id: ${JSON.stringify(loadTest.id)} },
};
const PAYLOAD = ${hasBody ? JSON.stringify(loadTest.body) : 'null'};

export default function () {
  const res = http.request(${JSON.stringify(loadTest.method)}, TARGET_URL, PAYLOAD, PARAMS);
  check(res, {
    'status is 2xx or 3xx': (r) => r.status >= 200 && r.status < 400,
  });
}
`;
  }

  /**
   * Resolves target URL by combining baseUrl and relative paths and appending query params.
   */
  resolveTargetUrl(
    url: string,
    baseUrl?: string | null,
    queryParams?: any,
  ): string {
    let finalUrl = url.trim();

    if (!finalUrl.startsWith('http://') && !finalUrl.startsWith('https://')) {
      if (baseUrl && baseUrl.trim().length > 0) {
        const cleanBase = baseUrl.trim().replace(/\/+$/, '');
        const cleanPath = finalUrl.startsWith('/') ? finalUrl : `/${finalUrl}`;
        finalUrl = `${cleanBase}${cleanPath}`;
      } else {
        finalUrl = `http://${finalUrl}`;
      }
    }

    // Append query params if present
    if (queryParams && typeof queryParams === 'object' && Object.keys(queryParams).length > 0) {
      try {
        const urlObj = new URL(finalUrl);
        for (const [key, val] of Object.entries(queryParams)) {
          if (val !== undefined && val !== null && val !== '') {
            urlObj.searchParams.set(key, String(val));
          }
        }
        finalUrl = urlObj.toString();
      } catch {
        // If URL parsing fails, string append
        const queryStr = Object.entries(queryParams)
          .filter(([_, v]) => v !== undefined && v !== null && v !== '')
          .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v))}`)
          .join('&');
        if (queryStr) {
          finalUrl += (finalUrl.includes('?') ? '&' : '?') + queryStr;
        }
      }
    }

    return finalUrl;
  }

  /**
   * Resolves request headers including authentication.
   */
  resolveHeaders(
    customHeaders?: any,
    authConfig?: any,
    method?: string,
  ): Record<string, string> {
    const headers: Record<string, string> = {};

    if (['POST', 'PUT', 'PATCH'].includes(method || 'GET')) {
      headers['Content-Type'] = 'application/json';
    }

    if (customHeaders && typeof customHeaders === 'object') {
      for (const [key, val] of Object.entries(customHeaders)) {
        if (val !== undefined && val !== null) {
          headers[key] = String(val);
        }
      }
    }

    // Apply authentication
    if (authConfig && typeof authConfig === 'object') {
      const type = authConfig.type;
      if (type === 'bearer' && authConfig.token) {
        headers['Authorization'] = `Bearer ${authConfig.token.trim()}`;
      } else if (type === 'basic' && (authConfig.username || authConfig.password)) {
        const user = authConfig.username || '';
        const pass = authConfig.password || '';
        const creds = Buffer.from(`${user}:${pass}`).toString('base64');
        headers['Authorization'] = `Basic ${creds}`;
      } else if (type === 'apiKey' && authConfig.key && authConfig.value) {
        if (authConfig.addTo !== 'query') {
          headers[authConfig.key] = authConfig.value;
        }
      }
    }

    return headers;
  }
}
